    void AnnotIconsLoad()
    {
        if (gLoaded)
        {
            // Recarregar não pode duplicar a tabela.
            AnnotIconsUnload();
        }

        gTextures.reserve(kCount);
        for (int i = 0; i < kCount; ++i)
        {
            Texture2D tex = { 0, 0, 0, 0, 0 };
            const std::string svg = MakeSvg(kDefs[i].paths);
            NSVGimage* img = nsvgParse((char*)svg.c_str(), "px", 96.0f);
            if (img)
            {
                // 96px de rasterização: glifos nítidos mesmo no print 2x
                // (o ícone é desenhado entre 20 e 44px na tela).
                const float iw = img->width;
                const float ih = img->height;
                const float scale = 96.0f / std::max(iw, ih);
                const int rw = (int)(iw * scale + 0.5f);
                const int rh = (int)(ih * scale + 0.5f);

                std::vector<unsigned char> rgba((size_t)rw * rh * 4, 0);
                NSVGrasterizer* rast = nsvgCreateRasterizer();
                if (rast)
                {
                    nsvgRasterize(rast, img, 0.0f, 0.0f, scale,
                                  rgba.data(), rw, rh, rw * 4);
                    nsvgDeleteRasterizer(rast);
                }
                nsvgDelete(img);

                Image im = {};
                im.data = rgba.data();
                im.width = rw;
                im.height = rh;
                im.mipmaps = 1;
                im.format = PIXELFORMAT_UNCOMPRESSED_R8G8B8A8;
                tex = LoadTextureFromImage(im);
                SetTextureFilter(tex, TEXTURE_FILTER_BILINEAR);
            }
            else
            {
                TraceLog(LOG_WARNING, "AnnotIcons: SVG invalido (%s)",
                         kDefs[i].file);
            }
            gTextures.push_back(tex);
        }
        gLoaded = true;
        TraceLog(LOG_INFO, "AnnotIcons: %d icones carregados", kCount);
    }

    void AnnotIconsUnload()
    {
        for (Texture2D& tex : gTextures)
            if (tex.id != 0) UnloadTexture(tex);
        gTextures.clear();
        gLoaded = false;
    }

    int AnnotIconCount() { return kCount; }

    const char* AnnotIconName(int index)
    {
        if (index < 1 || index > kCount) return "";
        return kDefs[index - 1].name;
    }

    const char* AnnotIconFileName(int index)
    {
        if (index < 1 || index > kCount) return "";
        return kDefs[index - 1].file;
    }

    Texture2D AnnotIconTexture(int index)
    {
        if (index < 1 || index > (int)gTextures.size()) return Texture2D{};
        return gTextures[index - 1];
    }

    bool AnnotIconImageButton(int index, float size, ImU32 tint,
                              const char* tooltip)
    {
        const Texture2D tex = AnnotIconTexture(index);
        if (tex.id == 0) return false;

        // Botão quadrado transparente com o ícone tingido por cima.
        char idbuf[32];
        snprintf(idbuf, sizeof idbuf, "##annot_icon_%d", index);
        bool clicked = ImGui::Button(idbuf, ImVec2(size, size));
        ImDrawList* dl = ImGui::GetWindowDrawList();
        const ImVec2 p0 = ImGui::GetItemRectMin();
        const ImVec2 p1 = ImGui::GetItemRectMax();
        const float pad = size * 0.14f;
        dl->AddImage((ImTextureID)(intptr_t)tex.id,
                     ImVec2(p0.x + pad, p0.y + pad),
                     ImVec2(p1.x - pad, p1.y - pad),
                     ImVec2(0, 0), ImVec2(1, 1), tint);
        if (tooltip && ImGui::IsItemHovered())
            ImGui::SetTooltip("%s", tooltip);
        return clicked;
    }

    void AnnotIconDrawOverlay(int index, const ImVec2& pos, float size,
                              ImU32 tint)
    {
        const Texture2D tex = AnnotIconTexture(index);
        if (tex.id == 0) return;
        ImDrawList* dl = ImGui::GetForegroundDrawList();
        dl->AddImage((ImTextureID)(intptr_t)tex.id, pos,
                     ImVec2(pos.x + size, pos.y + size),
                     ImVec2(0, 0), ImVec2(1, 1), tint);
    }
