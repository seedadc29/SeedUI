        std::vector<Texture2D> gTextures;
        bool gLoaded = false;

        std::string MakeSvg(const char* paths)
        {
            std::string svg;
            svg.reserve(256 + strlen(paths));
            svg += "<svg xmlns=\"http://www.w3.org/2000/svg\" width=\"24\" "
                   "height=\"24\" viewBox=\"0 0 24 24\" "
                   "fill=\"#ffffff\"><path d=\"";
            svg += paths;
            svg += "\"/></svg>";
            return svg;
        }
